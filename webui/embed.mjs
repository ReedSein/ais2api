// Turn Vite output into byte arrays: no runtime files, C++ string-size limits,
// source maps, or filesystem routing in the native HTTP server.
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, extname, join, resolve } from 'node:path'

const [distArg, outputArg] = process.argv.slice(2)
if (!distArg || !outputArg) throw new Error('Usage: node embed.mjs DIST OUTPUT')
const dist = resolve(distArg)
const output = resolve(outputArg)
const types = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json',
  '.txt': 'text/plain; charset=utf-8',
}

async function files(directory, prefix = '') {
  const result = []
  for (const item of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const relative = prefix + item.name
    if (item.isDirectory()) result.push(...await files(join(directory, item.name), relative + '/'))
    else if (item.isFile() && types[extname(item.name)]) result.push(relative)
    else throw new Error(`Unexpected WebUI asset: ${relative}`)
  }
  return result
}
const paths = await files(dist)
if (!paths.includes('index.html')) throw new Error('WebUI index.html is missing')
let generated = '// Generated by webui/embed.mjs; do not edit.\n'
const entries = []
for (const [index, path] of paths.entries()) {
  if (!/^[A-Za-z0-9_./-]+$/.test(path)) throw new Error(`Unsafe asset name: ${path}`)
  const data = await readFile(join(dist, path))
  if (!data.length || data.length > 4 * 1024 * 1024) throw new Error(`Invalid asset size: ${path}`)
  generated += `static const unsigned char asset_${index}[] = {\n`
  for (let offset = 0; offset < data.length; offset += 32) {
    generated += Array.from(data.subarray(offset, offset + 32), byte => `0x${byte.toString(16).padStart(2, '0')}`).join(',') + ',\n'
  }
  generated += '};\n'
  entries.push(`{${JSON.stringify('/' + path)}, ${JSON.stringify(types[extname(path)])}, {reinterpret_cast<const char*>(asset_${index}), sizeof(asset_${index})}, ${path.startsWith('assets/')}}`)
}
generated += `static const Asset assets[] = {\n${entries.join(',\n')}\n};\n`
await mkdir(dirname(output), { recursive: true })
await writeFile(output, generated)
console.log(`Embedded ${paths.length} WebUI assets`)
